'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const contract = require('../contract.js');

const FILE = 'wyarden-monitor.json';
const EVENTS = Object.freeze([
  'SessionStart', 'SessionEnd', 'UserPromptSubmit', 'Stop', 'StopFailure', 'StopCancelled',
  'PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'PermissionDenied', 'Notification'
]);
const ownFile = dir => path.join(dir, 'hooks', FILE);
const planned = new WeakSet();

function configDirs({ home = os.homedir(), env = process.env } = {}) {
  const override = env?.GROK_HOME;
  const dir = typeof override === 'string' && override.trim() ? path.resolve(override) : path.join(home, '.grok');
  try { return fs.statSync(dir).isDirectory() ? [dir] : []; } catch { return []; }
}

function document(url) {
  const handler = { type: 'http', url, timeout: 1 };
  const hooks = Object.fromEntries(EVENTS.map(event => [event, [{ hooks: [handler] }]]));
  return JSON.stringify({ hooks }, null, 2) + '\n';
}

const isGrokUrl = url => contract.isHookUrl(url) && url.endsWith('/grok');

function read(file) {
  try {
    const stat = fs.lstatSync(file);
    // This file is generated and small. Refuse oversized files and links in this reserved slot.
    if (!stat.isFile() || stat.size > 16384) return { error: 'the hook path is not a small regular file' };
    return { before: fs.readFileSync(file, 'utf8'), exists: true };
  } catch (error) {
    if (error.code === 'ENOENT') return { before: '', exists: false };
    return { error: 'the hook file could not be read' };
  }
}

function owned(text) {
  let url;
  try { url = JSON.parse(text)?.hooks?.SessionStart?.[0]?.hooks?.[0]?.url; } catch { return false; }
  // Comparing the generated bytes protects even manual additions or duplicate JSON keys.
  return isGrokUrl(url) && text === document(url);
}

function planConfig(hub, { dirs = configDirs(), mode = 'add' } = {}) {
  if (mode !== 'add' && mode !== 'remove') throw new TypeError('Invalid Grok hook install mode');
  const url = hub && contract.hookUrl(hub, 'grok');
  if (mode === 'add' && !isGrokUrl(url)) throw new TypeError('Grok hooks need a valid loopback hub');
  const desired = isGrokUrl(url) ? document(url) : null;
  return Array.from(new Set(dirs), dir => {
    const file = ownFile(dir);
    const current = read(file);
    const { before = '', exists = false } = current;
    const change = {
      dir, file, exists, before, after: before, changed: false, state: 'missing',
      error: null, reformatted: false, added: 0, replaced: 0, collapsed: 0, removed: 0
    };
    if (current.error || (exists && !owned(before))) {
      change.state = 'unreadable';
      change.error = current.error || 'The Grok hook file differs from the file created by Wyarden.';
    } else {
      if (exists) change.state = desired === null || before === desired ? 'installed' : 'stale';
      if (mode === 'remove' && exists) {
        change.after = '';
        change.removed = EVENTS.length;
      } else if (mode === 'add' && before !== desired) {
        change.after = desired;
        change[exists ? 'replaced' : 'added'] = EVENTS.length;
      }
      change.changed = change.before !== change.after;
    }
    planned.add(change);
    return Object.freeze(change);
  });
}

function status(dirs, hub, _options = {}) {
  const changes = planConfig(hub, { dirs, mode: 'remove' });
  const count = state => changes.filter(change => change.state === state).length;
  const folders = changes.length;
  const installed = count('installed');
  const stale = count('stale');
  const state = folders && installed === folders ? 'installed' : installed || stale ? 'partly' : 'missing';
  return { state, folders, installed, stale, unreadable: count('unreadable') };
}

function apply(changes) {
  return Array.from(changes, change => {
    const file = change?.file;
    const result = (written, reason) => ({ file, written, reason });
    if (!planned.has(change)) return result(false, 'not a change made by the Grok planner');
    if (change.error || !change.changed) return result(false, change.error || 'no change');

    const folder = path.dirname(file);
    let temp;
    try {
      if (change.after) {
        try { fs.mkdirSync(folder, { mode: 0o700 }); } catch (error) {
          if (error.code !== 'EEXIST') throw error;
        }
        temp = path.join(folder, '.' + FILE + '.' + randomUUID() + '.tmp');
        fs.writeFileSync(temp, change.after, { flag: 'wx', mode: 0o600, flush: true });
      }
      const current = read(file);
      if (current.error || current.exists !== change.exists || current.before !== change.before) {
        return result(false, 'changed since it was shown');
      }
      if (!change.after) fs.unlinkSync(file);
      else if (change.exists) fs.renameSync(temp, file);
      else fs.linkSync(temp, file);
      return result(true, null);
    } catch (error) {
      if (error.code === 'EEXIST') return result(false, 'changed since it was shown');
      return result(false, 'the Grok hook file could not be changed (' + (error.code || 'error') + ')');
    } finally {
      if (temp) { try { fs.unlinkSync(temp); } catch { /* already published or never created */ } }
    }
  });
}

module.exports = { EVENTS, configDirs, planConfig, status, apply };
